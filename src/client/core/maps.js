// Start groups for a map with four corner starts: a, b along the top,
// c, d along the bottom.
function groupsFor(a, b, c, d) {
  const p = (xy) => ({ x: xy[0], y: xy[1] });
  return {
    2: { '': [[p(a)], [p(d)]] },
    3: { '': [[p(a)], [p(b)], [p(d)]], 2: [[p(d)], [p(a), p(b)]] },
    4: {
      '': [[p(a)], [p(b)], [p(c)], [p(d)]],
      '2+2': [[p(a), p(b)], [p(c), p(d)]],
      3: [[p(d)], [p(a), p(b), p(c)]],
    },
  };
}

// Just the map data, for a game's setup.
export function mapData(map) {
  const { starts, ...data } = map;
  return data;
}
