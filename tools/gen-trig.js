// Writes src/rules/math/trig-table.js: sin of each whole degree, in ONE
// units. The table is committed, so the rules never call Math.sin.
// Only 0°–90° are computed; the rest are mirrored from them, so the
// table is exactly symmetric.
//
//   node tools/gen-trig.js

import { writeFileSync } from 'node:fs';
import { ONE } from '../src/rules/math/fixed.js';

const quarter = [];
for (let d = 0; d <= 90; d++) quarter.push(Math.round(Math.sin((d * Math.PI) / 180) * ONE));

const sin = [];
for (let d = 0; d < 360; d++) {
  if (d <= 90) sin.push(quarter[d]);
  else if (d <= 180) sin.push(quarter[180 - d]);
  else if (d <= 270) sin.push(-quarter[d - 180]);
  else sin.push(-quarter[360 - d]);
}

const rows = [];
for (let d = 0; d < 360; d += 10) rows.push('  ' + sin.slice(d, d + 10).join(', ') + ',');

const source = `// SPDX-License-Identifier: AGPL-3.0-or-later
// Copyright (C) 2026 Chad Johnson

// Generated by tools/gen-trig.js. Don't edit by hand.
// sin of each whole degree, 0° to 359°, in ONE (65536) units.
export const SIN_TABLE = Object.freeze([
${rows.join('\n')}
]);
`;

writeFileSync(new URL('../src/rules/math/trig-table.js', import.meta.url), source);
